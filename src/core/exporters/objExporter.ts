import * as THREE from 'three';

/**
 * Valid Wavefront OBJ Exporter with vertex normals and UVs
 */
export function exportOBJ(geometry: THREE.BufferGeometry, objectName: string = 'KineticForgeMesh'): Blob {
  const pos = geometry.attributes.position;
  const norm = geometry.attributes.normal;
  const uv = geometry.attributes.uv;
  const index = geometry.getIndex();

  let output = `# Wavefront OBJ File generated by KINETIC FORGE 3D\n`;
  output += `# Vertices: ${pos.count}\n`;
  output += `o ${objectName}\n\n`;

  // Write Vertices (remap Y-up to Z-up for 3D printing convention)
  for (let i = 0; i < pos.count; i++) {
    const x = pos.getX(i);
    const y = pos.getY(i);
    const z = pos.getZ(i);
    output += `v ${x.toFixed(4)} ${(-z).toFixed(4)} ${y.toFixed(4)}\n`;
  }

  // Write Normals
  if (norm) {
    output += `\n`;
    for (let i = 0; i < norm.count; i++) {
      const nx = norm.getX(i);
      const ny = norm.getY(i);
      const nz = norm.getZ(i);
      output += `vn ${nx.toFixed(4)} ${(-nz).toFixed(4)} ${ny.toFixed(4)}\n`;
    }
  }

  // Write UVs
  if (uv) {
    output += `\n`;
    for (let i = 0; i < uv.count; i++) {
      output += `vt ${uv.getX(i).toFixed(4)} ${uv.getY(i).toFixed(4)}\n`;
    }
  }

  // Write Faces (1-indexed)
  output += `\ns 1\n`;
  const numFaces = index ? index.count / 3 : pos.count / 3;

  for (let f = 0; f < numFaces; f++) {
    let i1 = f * 3 + 1;
    let i2 = f * 3 + 2;
    let i3 = f * 3 + 3;

    if (index) {
      i1 = index.getX(f * 3) + 1;
      i2 = index.getX(f * 3 + 1) + 1;
      i3 = index.getX(f * 3 + 2) + 1;
    }

    if (norm && uv) {
      output += `f ${i1}/${i1}/${i1} ${i2}/${i2}/${i2} ${i3}/${i3}/${i3}\n`;
    } else if (norm) {
      output += `f ${i1}//${i1} ${i2}//${i2} ${i3}//${i3}\n`;
    } else {
      output += `f ${i1} ${i2} ${i3}\n`;
    }
  }

  return new Blob([output], { type: 'text/plain' });
}
